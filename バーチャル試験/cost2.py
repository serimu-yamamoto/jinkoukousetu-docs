# 工事費 第2版：GPT監査を反映した断面、単価は根拠URL付きの調査値（直接工事費、税抜、地区・時点補正なし）
import numpy as np
A=40000
def est(ang):
    b=np.radians(ang); Ah=A*np.cos(b)*1.1
    h=0.55 if ang==20 else 0.58
    Vbench=A*np.cos(b)*h/2
    nx=int(np.ceil(1000/(10 if ang==20 else 15))); Lx=nx*40
    bed=10000*0.8+30000*0.45; bed_t=bed*1.674
    P=[]  # (項目, 下限, 上限, 根拠)
    P.append(("伐木＋除根",Ah*(36.081+41.529),Ah*(151.07+41.529),"施工P No.183/184"))
    P.append(("表土はぎ0.2m＋場内運搬1km",Ah*0.2*(163.70+496.00),Ah*0.2*(331.59+1050.3),"施工P No.001/002"))
    P.append((f"段切り掘削 {Vbench:,.0f}m³（高さ{h}m）",Vbench*331.59,Vbench*3534.5,"施工P 掘削〜片切掘削"))
    P.append(("法面整形",A*918.97,A*(4014.8 if ang==30 else 1197.1),"施工P 法面整形"))
    P.append((f"段差の充塡 構造用砕石C-40 {Vbench:,.0f}m³",Vbench*1.2*2400,Vbench*1.2*2850,"栃木R7単価表"))
    P.append(("下部フィルター（地山側）0.2〜0.3m",A*0.2*1.2*4200,A*0.3*1.2*4650,"栃木R7 単粒度6号（粒度は要照査）"))
    P.append(("排水層 砕石40-20mm 0.2m",A*0.2*1.2*4050,A*0.2*1.2*4700,"長崎サイカイ／茨城R6"))
    P.append(("上部フィルター 0.15m",A*0.15*1.2*4200,A*0.15*1.2*4650,"栃木R7 単粒度6号"))
    P.append((f"床材 方解石粒 {bed_t:,.0f}t（集中0.8m＋他0.45m）",bed_t*4200,bed_t*30000,"下限：砕砂4,200円/t（久米田）／上限：炭カル600円/20kg（石川R7）"))
    P.append((f"横断暗渠φ200 {nx}本×40m＝{Lx:,}m",Lx*(2940+5064.1),Lx*(2940+5064.1),"新潟R8.3＋施工P"))
    P.append(("縦断集水管φ150 両側2km",2000*(1820+837.85),2000*(1820+837.85),"新潟R8.3＋施工P No.093"))
    P.append(("端部 ふとんかご 両側2km",2000*13617,2000*14195,"施工P No.131"))
    P.append(("回収・調整池4,000m³（掘削＋石積1,000m²）",4000*331.59+1000*12531,4000*1050.3+1000*22207,"施工P No.001/064/062"))
    P.append(("細霧散水設備（全面）",A*1046,A*3876,"散水機ドットコム"))
    P.append(("センサー100か所",100*12923,100*27123,"スイッチサイエンス／Ubibot"))
    P.append(("地盤調査（ボーリング10本×15m＋土質試験）",1.57e6,2.64e6,"sphold／sg3／GBRC"))
    P.append(("圧雪車1〜2台",5e7,1e8,"グランスノー奥伊吹"))
    P.append(("施工時の石灰（消石灰27t）",27e3*59,27e3*59,"サンデー通販"))
    U=[]  # 単価未調査（GPTの仮単価、市場価格ではない）
    U.append(("両側の大型排水路・落差工 2km",2000*3e4,2000*10e4))
    U.append(("中和・制御設備",5e6,2e7))
    U.append(("沈殿池の拡張（表面積約2,160m²）",0,0))
    if ang==30: U.append((f"横断止め（地山に定着）{Lx:,}m",Lx*2e4,Lx*8e4))
    O=[("凍上性の地山の置換0.3m（必要な場合）",A*0.3*(1.2*2400+163.7),A*0.3*(1.2*2850+331.59),"栃木R7 C-40＋施工P掘削")]
    return P,U,O
for ang in [20,30]:
    P,U,O=est(ang)
    lo=sum(x[1] for x in P); hi=sum(x[2] for x in P)
    ulo=sum(x[1] for x in U); uhi=sum(x[2] for x in U)
    print(f"\n===== {ang}° =====")
    for n,a,b_,s in P: print(f"  {n:<44}{a/1e4:8,.0f}〜{b_/1e4:8,.0f}万円 [{s}]")
    print(f"  ─ 調査単価の直接工事費 {lo/1e8:.2f}〜{hi/1e8:.2f}億円")
    for n,a,b_ in U: print(f"  （未調査・GPT仮単価）{n:<34}{a/1e4:8,.0f}〜{b_/1e4:8,.0f}万円")
    for n,a,b_,s in O: print(f"  （条件付き）{n:<36}{a/1e4:8,.0f}〜{b_/1e4:8,.0f}万円 [{s}]")
    tl=(lo+ulo); th=(hi+uhi+O[0][2])
    print(f"  ─ 直接工事費の合計（仮単価分を含む） {tl/1e8:.2f}〜{th/1e8:.2f}億円")
    print(f"  ─ 工事代金の予測（諸経費×1.3〜1.6〔仮定〕、消費税10%） {tl*1.3*1.1/1e8:.1f}〜{th*1.6*1.1/1e8:.1f}億円")
